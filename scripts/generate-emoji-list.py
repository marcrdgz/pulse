#!/usr/bin/env python3
"""Writes Pulse/Resources/Emoji.txt, the emoji the space icon picker offers, from Unicode's emoji-test.txt.

Usage: scripts/generate-emoji-list.py [emoji version]

Keep the version at or below what the deployment target's system font draws (Emoji 16.0 for macOS 15.4),
or new emoji show up as empty boxes. Skin tone variants and the Component group are left out:
the picker shows each emoji once, in its default tone.
"""
import pathlib
import sys
import urllib.request

version = sys.argv[1] if len(sys.argv) > 1 else "16.0"
url = f"https://unicode.org/Public/emoji/{version}/emoji-test.txt"
skin_tones = {chr(code) for code in range(0x1F3FB, 0x1F400)}

lines = [f"# Generated by scripts/generate-emoji-list.py from Emoji {version}; do not edit."]
group = None
with urllib.request.urlopen(url) as response:
    for line in response.read().decode("utf-8").splitlines():
        if line.startswith("# group: "):
            group = line.removeprefix("# group: ")
            if group != "Component":
                lines.append(f"## {group}")
            continue
        if group == "Component" or "; fully-qualified" not in line:
            continue
        # "1F600 ; fully-qualified # 😀 E1.0 grinning face"
        emoji, _, name = line.split("# ", 1)[1].partition(" ")
        if skin_tones.intersection(emoji):
            continue
        name = name.split(" ", 1)[1]
        lines.append(f"{emoji}\t{name}")

output = pathlib.Path(__file__).resolve().parent.parent / "Pulse/Resources/Emoji.txt"
output.write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"Wrote {sum(1 for line in lines if not line.startswith('#'))} emoji to {output}")
